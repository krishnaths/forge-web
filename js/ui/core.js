// ---------------------------------------------------------------- toasts (the phone's snackbar)

const toastListeners = new Set();
export const toast = message => toastListeners.forEach(fn => fn(message));

export function Toasts() {
  const [msg, setMsg] = useState(null);
  useEffect(() => {
    let timer;
    const show = m => { setMsg(m); clearTimeout(timer); timer = setTimeout(() => setMsg(null), 3500); };
    toastListeners.add(show);
    return () => toastListeners.delete(show);
  }, []);
  return msg ? html`<div class="toast" role="status">${msg}</div>` : null;
}

